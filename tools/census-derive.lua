-- census-derive.lua — measure a markdown corpus and generate
-- lua/nightfox/census/markdown.lua: per-class density statistics and the
-- class-adjacency graph the lynx allocator derives from (autocolors #2).
--
--   CORPUS=/path/to/filelist nvim --headless -l tools/census-derive.lua
--
-- Classes are capture names aggregated across languages (per-language
-- sibling schemes are P4; this feeds the language-agnostic allocator).
-- Meta captures (@spell/@nospell/@conceal/@none/@_*) are dropped: they are
-- spellcheck/conceal machinery, not visual classes.
-- Adjacency: consecutive distinct-class span pairs in byte order, all
-- injection layers interleaved — the visual neighbor truth of the page.

-- rtp: this fork (its after/queries extensions are part of what we measure),
-- the parser site dir, and any vendored nvim-treesitter (queries for
-- injected languages) — the census must see what the editor sees.
local here = vim.fn.fnamemodify(debug.getinfo(1).source:sub(2), ":p:h:h")
vim.opt.rtp:prepend(here)
vim.opt.rtp:append(here .. "/after") -- after/queries extensions live here
vim.opt.rtp:append(vim.fn.stdpath("data") .. "/site")
for _, pk in ipairs(vim.fn.glob(vim.fn.stdpath("config") .. "/pack/*/start/nvim-treesitter", true, true)) do
  vim.opt.rtp:append(pk)
end

local files = {}
for line in io.lines(os.getenv("CORPUS")) do
  files[#files + 1] = line
end

local META = { ["@spell"] = true, ["@nospell"] = true, ["@conceal"] = true, ["@none"] = true }
local function is_meta(name)
  return META[name] or name:match("^@_")
end

local classes = {} -- name -> {n, bytes}  (aggregated across languages)
local lang_classes = {} -- "@capture.lang" for injected langs beyond markdown/_inline
local adj = {} -- "a\tb" (sorted) -> weight
local total = 0

for _, file in ipairs(files) do
  local bufnr = vim.fn.bufnr(file, true)
  if pcall(vim.fn.bufload, bufnr) and vim.fn.getfsize(file) > 0 then
    total = total + vim.fn.getfsize(file)
    local ok, parser = pcall(vim.treesitter.get_parser, bufnr, "markdown")
    if ok and parser then
      parser:parse(true)
      local spans = {}
      parser:for_each_tree(function(tstree, ltree)
        local q = vim.treesitter.query.get(ltree:lang(), "highlights")
        if q then
          for id, node in q:iter_captures(tstree:root(), bufnr, 0, -1) do
            local name = "@" .. q.captures[id]
            if not is_meta(name) then
              local _, _, sb, _, _, eb = node:range(true)
              local c = classes[name] or { n = 0, bytes = 0 }
              c.n, c.bytes = c.n + 1, c.bytes + (eb - sb)
              classes[name] = c
              local lang = ltree:lang()
              if lang ~= "markdown" and lang ~= "markdown_inline" then
                local lname = name .. "." .. lang
                local lc = lang_classes[lname] or { n = 0, bytes = 0 }
                lc.n, lc.bytes = lc.n + 1, lc.bytes + (eb - sb)
                lang_classes[lname] = lc
              end
              spans[#spans + 1] = { sb, eb, name }
            end
          end
        end
      end)
      table.sort(spans, function(a, b)
        if a[1] ~= b[1] then return a[1] < b[1] end
        return a[2] > b[2] -- outer span first at same start
      end)
      -- consecutive distinct-class neighbors (skip nested same-start dups)
      for i = 2, #spans do
        local a, b = spans[i - 1][3], spans[i][3]
        if a ~= b then
          local key = a < b and (a .. "\t" .. b) or (b .. "\t" .. a)
          adj[key] = (adj[key] or 0) + 1
        end
      end
    end
  end
end

-- emit generated lua
local out = {}
local function w(s)
  out[#out + 1] = s
end
w("-- GENERATED by tools/census-derive.lua — do not hand-edit.")
w(("-- corpus: %d files, %d bytes; regenerate: CORPUS=<filelist> nvim --headless -l tools/census-derive.lua"):format(#files, total))
w(("-- generated: %s"):format(os.date("%Y-%m-%d")))
w("return {")
w(("  meta = { files = %d, bytes = %d },"):format(#files, total))
w("  classes = {")
local names = {}
for k in pairs(classes) do
  names[#names + 1] = k
end
table.sort(names)
for _, name in ipairs(names) do
  local c = classes[name]
  local share = c.bytes / total
  local density10k = c.n / (total / 10000)
  local avg_len = c.bytes / c.n
  w(('    ["%s"] = { share = %.6f, density10k = %.3f, avg_len = %.1f, n = %d, bytes = %d },'):format(
    name, share, density10k, avg_len, c.n, c.bytes))
end
w("  },")
w("  lang_classes = {")
local lnames = {}
for k in pairs(lang_classes) do
  lnames[#lnames + 1] = k
end
table.sort(lnames)
for _, name in ipairs(lnames) do
  local c = lang_classes[name]
  w(('    ["%s"] = { share = %.6f, density10k = %.3f, avg_len = %.1f, n = %d, bytes = %d },'):format(
    name, c.bytes / total, c.n / (total / 10000), c.bytes / c.n, c.n, c.bytes))
end
w("  },")
w("  adjacency = {")
local pairs_sorted = {}
for k, v in pairs(adj) do
  pairs_sorted[#pairs_sorted + 1] = { k, v }
end
table.sort(pairs_sorted, function(a, b)
  return a[2] > b[2]
end)
for i = 1, math.min(#pairs_sorted, 120) do
  local a, b = pairs_sorted[i][1]:match("^(.-)\t(.+)$")
  w(('    { "%s", "%s", %d },'):format(a, b, pairs_sorted[i][2]))
end
w("  },")
w("}")

vim.fn.mkdir("lua/nightfox/census", "p")
local f = io.open("lua/nightfox/census/markdown.lua", "w")
f:write(table.concat(out, "\n") .. "\n")
f:close()
print(("wrote lua/nightfox/census/markdown.lua: %d classes, %d adjacency pairs (top 120 kept)"):format(#names, #pairs_sorted))
